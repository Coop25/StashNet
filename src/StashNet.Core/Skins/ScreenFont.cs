using System.Collections.Generic;

namespace StashNet.Core.Skins
{
    /// <summary>5x7 bitmap glyphs for the terminal screen. Unknown characters draw nothing.</summary>
    public static class ScreenFont
    {
        public const int GlyphWidth = 5;
        public const int GlyphHeight = 7;

        // Seven rows per glyph, '#' = lit.
        static readonly Dictionary<char, string[]> Glyphs = Build();

        /// <summary>True when the pixel (x 0-4, y 0-6 from the top) of the glyph is lit.</summary>
        public static bool IsLit(char c, int x, int y)
        {
            if (x < 0 || x >= GlyphWidth || y < 0 || y >= GlyphHeight) return false;
            return Glyphs.TryGetValue(char.ToUpperInvariant(c), out var rows) && rows[y][x] == '#';
        }

        static Dictionary<char, string[]> Build()
        {
            var d = new Dictionary<char, string[]>();
            void G(char c, string rows) => d[c] = rows.Split('/');
            G('A', ".###./#...#/#...#/#####/#...#/#...#/#...#");
            G('B', "####./#...#/#...#/####./#...#/#...#/####.");
            G('C', ".###./#...#/#..../#..../#..../#...#/.###.");
            G('D', "####./#...#/#...#/#...#/#...#/#...#/####.");
            G('E', "#####/#..../#..../####./#..../#..../#####");
            G('F', "#####/#..../#..../####./#..../#..../#....");
            G('G', ".###./#...#/#..../#.###/#...#/#...#/.####");
            G('H', "#...#/#...#/#...#/#####/#...#/#...#/#...#");
            G('I', ".###./..#../..#../..#../..#../..#../.###.");
            G('J', "..###/...#./...#./...#./...#./#..#./.##..");
            G('K', "#...#/#..#./#.#../##.../#.#../#..#./#...#");
            G('L', "#..../#..../#..../#..../#..../#..../#####");
            G('M', "#...#/##.##/#.#.#/#.#.#/#...#/#...#/#...#");
            G('N', "#...#/##..#/#.#.#/#..##/#...#/#...#/#...#");
            G('O', ".###./#...#/#...#/#...#/#...#/#...#/.###.");
            G('P', "####./#...#/#...#/####./#..../#..../#....");
            G('Q', ".###./#...#/#...#/#...#/#.#.#/#..#./.##.#");
            G('R', "####./#...#/#...#/####./#.#../#..#./#...#");
            G('S', ".####/#..../#..../.###./....#/....#/####.");
            G('T', "#####/..#../..#../..#../..#../..#../..#..");
            G('U', "#...#/#...#/#...#/#...#/#...#/#...#/.###.");
            G('V', "#...#/#...#/#...#/#...#/#...#/.#.#./..#..");
            G('W', "#...#/#...#/#...#/#.#.#/#.#.#/##.##/#...#");
            G('X', "#...#/#...#/.#.#./..#../.#.#./#...#/#...#");
            G('Y', "#...#/#...#/.#.#./..#../..#../..#../..#..");
            G('Z', "#####/....#/...#./..#../.#.../#..../#####");
            G('0', ".###./#...#/#..##/#.#.#/##..#/#...#/.###.");
            G('1', "..#../.##../..#../..#../..#../..#../.###.");
            G('2', ".###./#...#/....#/...#./..#../.#.../#####");
            G('3', "####./....#/....#/.###./....#/....#/####.");
            G('4', "...#./..##./.#.#./#..#./#####/...#./...#.");
            G('5', "#####/#..../####./....#/....#/#...#/.###.");
            G('6', ".###./#..../#..../####./#...#/#...#/.###.");
            G('7', "#####/....#/...#./..#../.#.../.#.../.#...");
            G('8', ".###./#...#/#...#/.###./#...#/#...#/.###.");
            G('9', ".###./#...#/#...#/.####/....#/....#/.###.");
            G('/', "....#/....#/...#./..#../.#.../#..../#....");
            G('%', "##..#/##..#/...#./..#../.#.../#..##/#..##");
            G('[', ".###./.#.../.#.../.#.../.#.../.#.../.###.");
            G(']', ".###./...#./...#./...#./...#./...#./.###.");
            G('(', "..#../.#.../#..../#..../#..../.#.../..#..");
            G(')', "..#../...#./....#/....#/....#/...#./..#..");
            G('.', "...../...../...../...../...../.##../.##..");
            G(',', "...../...../...../...../.##../..#../.#...");
            G(':', "...../.##../.##../...../.##../.##../.....");
            G(' ', "...../...../...../...../...../...../.....");
            return d;
        }
    }
}
